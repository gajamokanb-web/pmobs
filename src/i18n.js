var ATTRS=["aria-label","placeholder","title","alt"];
var FRSEG=/ · /;
function trCore(s){
  if(Object.prototype.hasOwnProperty.call(UI,s))return UI[s];
  for(var i=0;i<RX.length;i++){if(RX[i][0].test(s))return s.replace(RX[i][0],RX[i][1]);}
  return null;
}
function trStr(s){
  var m=/^(\s*)([\s\S]*?)(\s*)$/.exec(s), core=m[2];
  if(!core)return null;
  var r=trCore(core);
  if(r===null&&FRSEG.test(core)){
    var parts=core.split(" · "), any=false;
    parts=parts.map(function(p){var x=trCore(p);if(x===null)return p;any=true;return x;});
    if(any)r=parts.join(" · ");
  }
  return r===null?null:m[1]+r+m[3];
}
var tracked=[], obs=null, busy=false;
function trText(n){
  var v=n.nodeValue; if(!v||!/\S/.test(v))return;
  var r=trStr(v); if(r===null||r===v)return;
  tracked.push([n,v]); n.nodeValue=r;
}
function trEl(el){
  ATTRS.forEach(function(a){
    if(!el.hasAttribute||!el.hasAttribute(a))return;
    var v=el.getAttribute(a), r=trStr(v); if(r===null||r===v)return;
    tracked.push([el,v,a]); el.setAttribute(a,r);
  });
}
function trTree(root){
  if(root.nodeType===3){trText(root);return;}
  if(root.nodeType!==1)return;
  var tag=root.tagName; if(tag==="SCRIPT"||tag==="STYLE"||tag==="TEXTAREA")return;
  trEl(root);
  var w=document.createTreeWalker(root,NodeFilter.SHOW_TEXT|NodeFilter.SHOW_ELEMENT,null), n;
  while((n=w.nextNode())){
    if(n.nodeType===3){var p=n.parentNode&&n.parentNode.tagName;if(p==="SCRIPT"||p==="STYLE"||p==="TEXTAREA")continue;trText(n);}
    else trEl(n);
  }
}
function pruneTracked(){if(tracked.length>4000)tracked=tracked.filter(function(t){return t[0].isConnected;});}
function onMut(list){
  if(LANG!=="en"||busy)return;
  busy=true;
  try{
    list.forEach(function(r){
      if(r.type==="childList")r.addedNodes.forEach(trTree);
      else if(r.type==="characterData")trText(r.target);
      else if(r.type==="attributes")trEl(r.target);
    });
    pruneTracked();
  }finally{obs.takeRecords();busy=false;}
}
function startObs(){
  if(!window.MutationObserver)return;
  if(!obs)obs=new MutationObserver(onMut);
  obs.observe(document.body,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:ATTRS});
}
function untranslateAll(){
  busy=true;
  tracked.forEach(function(t){
    if(t.length===2){if(t[0].isConnected||true)t[0].nodeValue=t[1];}
    else t[0].setAttribute(t[2],t[1]);
  });
  tracked=[];
  if(obs)obs.takeRecords();
  busy=false;
}
